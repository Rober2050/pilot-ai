import PptxGenJS from 'pptxgenjs';
import {
    VERDICT_COLORS,
    SLIDE_BG,
    TEXT_H,
    TEXT_B,
    TEXT_M,
    BORDER,
    addCoverSlide,
    addClosingSlide,
    addSlideHeaderClean,
    addPremiumCard,
    normalizeVerdict,
    t,
} from '../pptHelpers';
import type { SynthesisOutput } from '../../../types/blueprint';

// Synthesis brand color — indigo (neutral, no role bias)
const SYNTH_COLOR  = '4F46E5';
const SYNTH_LIGHT  = '818CF8';
const SYNTH_PALE   = 'EDE9FE';

const SEVERITY_COLORS: Record<string, { fill: string; text: string; label_es: string; label_en: string }> = {
    high:   { fill: 'FEF2F2', text: 'DC2626', label_es: 'ALTO',   label_en: 'HIGH' },
    medium: { fill: 'FFFBEB', text: 'D97706', label_es: 'MEDIO',  label_en: 'MEDIUM' },
    low:    { fill: 'EFF6FF', text: '2563EB', label_es: 'BAJO',   label_en: 'LOW' },
};

const LABELS_ES: Record<string, string> = {
    'Unified Executive Report':  'Informe Ejecutivo Unificado',
    'Team Synthesis':            'Síntesis del Equipo',
    'Team Verdict':              'Veredicto del Equipo',
    'Executive Summary':         'Resumen Ejecutivo',
    'Team Consensus':            'Consenso del Equipo',
    'Tension Points':            'Puntos de Tensión',
    'Top 3 Unified Risks':       'Top 3 Riesgos Unificados',
    'Recommendation':            'Recomendación',
    'Roles Analyzed':            'Roles Analizados',
    'Confidence':                'Confianza',
    'PROCEED':                   'PROCEDER',
    'PIVOT':                     'PIVOTAR',
    'HALT':                      'DETENER',
    'Generated on':              'Generado el',
    'Generated by PILOT AI':     'Generado por PILOT AI',
    'Risk':                      'Riesgo',
    'Sources':                   'Fuentes identificadas',
};

function ts(label: string, lang: 'es' | 'en'): string {
    return lang === 'es' ? (LABELS_ES[label] ?? label) : label;
}

function truncate(s: string, max: number): string {
    if (!s) return '';
    return s.length > max ? s.slice(0, max - 1) + '…' : s;
}

// ─── Slide 1: Cover ───────────────────────────────────────────────────────────
function buildCover(pptx: PptxGenJS, synthesis: SynthesisOutput, projectName: string, lang: 'es' | 'en') {
    const nv = normalizeVerdict(synthesis.teamVerdict);
    const dateStr = new Date().toLocaleDateString(lang === 'es' ? 'es-ES' : 'en-US', {
        year: 'numeric', month: 'long', day: 'numeric',
    });
    addCoverSlide(pptx, {
        title:       ts('Unified Executive Report', lang),
        subtitle:    ts('Team Synthesis', lang),
        projectName,
        date:        dateStr,
        verdict:     { verdict: nv, action: ts(nv, lang) },
        roleColor:   SYNTH_COLOR,
        lang,
    });
}

// ─── Slide 2: Team Verdict ────────────────────────────────────────────────────
function buildVerdictSlide(pptx: PptxGenJS, synthesis: SynthesisOutput, lang: 'es' | 'en', footer: string) {
    const slide = pptx.addSlide();
    slide.background = { color: SLIDE_BG };
    addSlideHeaderClean(slide, ts('Team Verdict', lang), SYNTH_COLOR, footer);

    const nv  = normalizeVerdict(synthesis.teamVerdict);
    const vc  = VERDICT_COLORS[nv] || SYNTH_COLOR;
    const conf = Math.min(100, Math.max(0, synthesis.verdictConfidence || 0));

    // Large verdict card
    addPremiumCard(slide, { x: 0.55, y: 1.05, w: 9.0, h: 1.55, accentColor: vc, accentSide: 'top' });
    slide.addText(ts(nv, lang), {
        x: 0.75, y: 1.1, w: 5.5, h: 1.45,
        fontSize: 52, bold: true, color: vc, fontFace: 'Helvetica', valign: 'middle',
    });
    // Confidence badge
    slide.addShape('roundRect', { x: 7.0, y: 1.55, w: 2.3, h: 0.65, fill: { color: SYNTH_PALE }, line: { color: SYNTH_LIGHT, width: 0.5 }, rectRadius: 0.12 });
    slide.addText(`${conf}%`, {
        x: 7.05, y: 1.55, w: 1.1, h: 0.65,
        fontSize: 22, bold: true, color: SYNTH_COLOR, fontFace: 'Helvetica', align: 'center', valign: 'middle',
    });
    slide.addText(ts('Confidence', lang).toUpperCase(), {
        x: 8.1, y: 1.55, w: 1.15, h: 0.65,
        fontSize: 9, bold: false, color: TEXT_M, fontFace: 'Helvetica', align: 'left', valign: 'middle', charSpacing: 0.3,
    });

    // Rationale text card
    const rationale = truncate(synthesis.verdictRationale || '', 320);
    addPremiumCard(slide, { x: 0.55, y: 2.75, w: 9.0, h: 2.65, accentColor: SYNTH_LIGHT, accentSide: 'left' });
    slide.addText(rationale, {
        x: 0.85, y: 2.85, w: 8.45, h: 2.45,
        fontSize: 14, color: TEXT_B, fontFace: 'Helvetica', valign: 'middle', wrap: true,
    });
}

// ─── Slide 3: Executive Summary ───────────────────────────────────────────────
function buildSummarySlide(pptx: PptxGenJS, synthesis: SynthesisOutput, lang: 'es' | 'en', footer: string) {
    const slide = pptx.addSlide();
    slide.background = { color: SLIDE_BG };
    addSlideHeaderClean(slide, ts('Executive Summary', lang), SYNTH_COLOR, footer);

    const summary = truncate(synthesis.executiveSummary || '', 800);
    addPremiumCard(slide, { x: 0.55, y: 1.05, w: 9.0, h: 4.3, accentColor: SYNTH_COLOR, accentSide: 'top' });
    slide.addText(summary, {
        x: 0.80, y: 1.25, w: 8.55, h: 3.90,
        fontSize: 13, color: TEXT_B, fontFace: 'Helvetica', wrap: true, valign: 'top',
    });
}

// ─── Slide 4: Team Consensus ──────────────────────────────────────────────────
function buildConsensusSlide(pptx: PptxGenJS, synthesis: SynthesisOutput, lang: 'es' | 'en', footer: string) {
    const slide = pptx.addSlide();
    slide.background = { color: SLIDE_BG };
    addSlideHeaderClean(slide, ts('Team Consensus', lang), SYNTH_COLOR, footer);

    const alignments = synthesis.alignments ?? [];
    if (alignments.length === 0) {
        slide.addText(lang === 'es' ? 'Sin consensos registrados.' : 'No consensus points recorded.', {
            x: 0.55, y: 2.5, w: 9.0, h: 0.5, fontSize: 13, color: TEXT_M, align: 'center',
        });
        return;
    }

    const itemH = 0.75;
    const startY = 1.10;
    const maxItems = Math.min(alignments.length, 6);

    alignments.slice(0, maxItems).forEach((a, i) => {
        const y = startY + i * (itemH + 0.1);
        addPremiumCard(slide, { x: 0.55, y, w: 9.0, h: itemH, accentColor: '059669', accentSide: 'left' });
        // Checkmark
        slide.addText('✓', { x: 0.70, y, w: 0.5, h: itemH, fontSize: 18, color: '059669', fontFace: 'Helvetica', valign: 'middle', align: 'center' });
        slide.addText(truncate(a.topic, 160), {
            x: 1.20, y, w: 8.10, h: itemH,
            fontSize: 12, color: TEXT_B, fontFace: 'Helvetica', valign: 'middle', wrap: true,
        });
    });
}

// ─── Slide 5: Tension Points ──────────────────────────────────────────────────
function buildTensionsSlide(pptx: PptxGenJS, synthesis: SynthesisOutput, lang: 'es' | 'en', footer: string) {
    const slide = pptx.addSlide();
    slide.background = { color: SLIDE_BG };
    addSlideHeaderClean(slide, ts('Tension Points', lang), SYNTH_COLOR, footer);

    const tensions = synthesis.tensions ?? [];
    if (tensions.length === 0) {
        slide.addText(lang === 'es' ? 'Sin tensiones detectadas.' : 'No tensions detected.', {
            x: 0.55, y: 2.5, w: 9.0, h: 0.5, fontSize: 13, color: TEXT_M, align: 'center',
        });
        return;
    }

    const maxItems = Math.min(tensions.length, 5);
    const itemH = 0.82;
    const startY = 1.10;

    tensions.slice(0, maxItems).forEach((tension, i) => {
        const y = startY + i * (itemH + 0.08);
        const sev = (tension.severity || 'medium') as 'high' | 'medium' | 'low';
        const sevCfg = SEVERITY_COLORS[sev] ?? SEVERITY_COLORS.medium;
        addPremiumCard(slide, { x: 0.55, y, w: 9.0, h: itemH, accentColor: sevCfg.text, accentSide: 'left', bgColor: sevCfg.fill });
        // Severity badge
        slide.addShape('roundRect', { x: 0.80, y: y + 0.22, w: 0.90, h: 0.35, fill: { color: sevCfg.text }, line: { color: sevCfg.text, width: 0 }, rectRadius: 0.06 });
        slide.addText(lang === 'es' ? sevCfg.label_es : sevCfg.label_en, {
            x: 0.80, y: y + 0.22, w: 0.90, h: 0.35,
            fontSize: 8, bold: true, color: 'FFFFFF', align: 'center', valign: 'middle', fontFace: 'Helvetica',
        });
        slide.addText(truncate(tension.description, 200), {
            x: 1.80, y, w: 7.55, h: itemH,
            fontSize: 11, color: TEXT_B, fontFace: 'Helvetica', valign: 'middle', wrap: true,
        });
    });
}

// ─── Slide 6: Top 3 Risks ─────────────────────────────────────────────────────
function buildRisksSlide(pptx: PptxGenJS, synthesis: SynthesisOutput, lang: 'es' | 'en', footer: string) {
    const slide = pptx.addSlide();
    slide.background = { color: SLIDE_BG };
    addSlideHeaderClean(slide, ts('Top 3 Unified Risks', lang), SYNTH_COLOR, footer);

    const risks = synthesis.topRisks ?? [];
    const maxRisks = Math.min(risks.length, 3);
    if (maxRisks === 0) {
        slide.addText(lang === 'es' ? 'Sin riesgos registrados.' : 'No risks recorded.', {
            x: 0.55, y: 2.5, w: 9.0, h: 0.5, fontSize: 13, color: TEXT_M, align: 'center',
        });
        return;
    }

    const riskColors = ['DC2626', 'D97706', 'D97706'];
    const cardH = 1.35;
    const startY = 1.10;

    risks.slice(0, maxRisks).forEach((risk, i) => {
        const y = startY + i * (cardH + 0.12);
        const col = riskColors[i] || riskColors[2];
        addPremiumCard(slide, { x: 0.55, y, w: 9.0, h: cardH, accentColor: col, accentSide: 'top' });

        // Rank circle
        slide.addShape('ellipse', { x: 0.70, y: y + 0.32, w: 0.60, h: 0.60, fill: { color: col }, line: { color: col, width: 0 } });
        slide.addText(String(risk.rank || i + 1), { x: 0.70, y: y + 0.32, w: 0.60, h: 0.60, fontSize: 18, bold: true, color: 'FFFFFF', align: 'center', valign: 'middle', fontFace: 'Helvetica' });

        // Risk text
        slide.addText(truncate(risk.description, 200), {
            x: 1.45, y: y + 0.12, w: 7.90, h: 0.75,
            fontSize: 12, bold: true, color: TEXT_H, fontFace: 'Helvetica', wrap: true, valign: 'top',
        });

        // Sources
        const sources = (risk.sourcedFrom ?? []).join(' · ');
        if (sources) {
            slide.addText(sources, {
                x: 1.45, y: y + 0.88, w: 7.90, h: 0.35,
                fontSize: 9, color: TEXT_M, fontFace: 'Helvetica', valign: 'top',
            });
        }
    });
}

// ─── Slide 7: Recommendation ──────────────────────────────────────────────────
function buildRecommendationSlide(pptx: PptxGenJS, synthesis: SynthesisOutput, projectName: string, lang: 'es' | 'en') {
    const slide = pptx.addSlide();
    slide.background = { color: SLIDE_BG };

    const rolesLabel = ts('Roles Analyzed', lang);
    const rolesStr = (synthesis.rolesAnalyzed ?? []).join(' · ') || '—';
    addSlideHeaderClean(slide, ts('Recommendation', lang), SYNTH_COLOR, `${projectName} | PILOT AI`);

    // Recommendation card
    addPremiumCard(slide, { x: 0.55, y: 1.05, w: 9.0, h: 2.60, accentColor: SYNTH_COLOR, accentSide: 'top', bgColor: 'F5F3FF' });
    slide.addText(truncate(synthesis.recommendation || '', 500), {
        x: 0.80, y: 1.20, w: 8.55, h: 2.35,
        fontSize: 14, color: TEXT_B, fontFace: 'Helvetica', wrap: true, valign: 'middle',
    });

    // Roles analyzed section
    addPremiumCard(slide, { x: 0.55, y: 3.80, w: 9.0, h: 1.55, accentColor: SYNTH_LIGHT, accentSide: 'none' });
    slide.addText(rolesLabel.toUpperCase(), {
        x: 0.80, y: 3.88, w: 8.55, h: 0.35,
        fontSize: 9, bold: false, color: TEXT_M, fontFace: 'Helvetica', charSpacing: 0.5,
    });
    slide.addText(rolesStr, {
        x: 0.80, y: 4.20, w: 8.55, h: 0.90,
        fontSize: 11, color: SYNTH_COLOR, fontFace: 'Helvetica', wrap: true, bold: true, valign: 'top',
    });

    // Closing line
    const dateStr = new Date().toLocaleDateString(lang === 'es' ? 'es-ES' : 'en-US', { year: 'numeric', month: 'long', day: 'numeric' });
    slide.addText(`${ts('Generated on', lang)} ${dateStr} · PILOT AI`, {
        x: 0.55, y: 5.25, w: 9.0, h: 0.30,
        fontSize: 9, color: TEXT_M, fontFace: 'Helvetica', align: 'center',
    });
}

// ─── Public API ───────────────────────────────────────────────────────────────
export const synthesisPPT = {
    generate: async (
        synthesis: SynthesisOutput,
        projectName: string = 'Project',
        lang: 'es' | 'en' = 'es'
    ): Promise<void> => {
        const pptx = new PptxGenJS();
        pptx.layout = 'LAYOUT_16x9';

        const footer = `${ts('Team Synthesis', lang).toUpperCase()} | ${projectName}`;

        buildCover(pptx, synthesis, projectName, lang);
        buildVerdictSlide(pptx, synthesis, lang, footer);
        buildSummarySlide(pptx, synthesis, lang, footer);
        buildConsensusSlide(pptx, synthesis, lang, footer);
        buildTensionsSlide(pptx, synthesis, lang, footer);
        buildRisksSlide(pptx, synthesis, lang, footer);
        buildRecommendationSlide(pptx, synthesis, projectName, lang);

        const filename = `${projectName.replace(/[^a-zA-Z0-9]/g, '_')}_Synthesis_${Date.now()}.pptx`;
        await pptx.writeFile({ fileName: filename });
    },
};
