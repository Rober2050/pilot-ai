import { Document, Packer, Paragraph, TextRun, HeadingLevel, AlignmentType, PageBreak } from "docx";
import { saveAs } from "file-saver";

interface GTMData {
    projectName?: string;
    summary?: string;
    industryBenchmarks?: {
        vertical?: string;
        avgCPC?: number;
        avgConversionRate?: number;
        avgCAC?: number;
        avgLTV?: number;
        source?: string;
    };
    buyerPersona?: {
        avatar?: string;
        painPoint?: string;
        demographics?: Record<string, string>;
        interests?: string[];
        behaviors?: string[];
        goals?: string[];
        objections?: string[];
    };
    messagingFramework?: {
        valueProposition?: string;
        elevatorPitch?: string;
        tagline?: string;
        keyMessages?: { audience: string; message: string; tone: string }[];
    };
    channelStrategy?: { canal: string; score: number; budgetPct?: number; rationale?: string; recommended?: boolean }[];
    roasScenarios?: {
        conservative?: { roas: number; monthlySales: number; cpc: number; convRate: number };
        base?: { roas: number; monthlySales: number; cpc: number; convRate: number };
        aggressive?: { roas: number; monthlySales: number; cpc: number; convRate: number };
    };
    unitEconomics?: {
        cac?: number; ltv?: number; ltvCacRatio?: number;
        paybackMonths?: number; monthlyChurn?: number; arpu?: number;
    };
    gtmCalendar?: { week: number | string; phase?: string; tasks?: string[]; subtasks?: string[] }[];
    tacticalFunnel?: { stage: string; metric: string; value: number | string; action: string }[];
}

// ─── Helper: create a section heading ──────────────────────────────────────
function h1(text: string, pageBreak = false): Paragraph {
    return new Paragraph({
        text,
        heading: HeadingLevel.HEADING_1,
        pageBreakBefore: pageBreak,
        spacing: { before: 300, after: 120 },
    });
}
function h2(text: string): Paragraph {
    return new Paragraph({
        text,
        heading: HeadingLevel.HEADING_2,
        spacing: { before: 240, after: 100 },
    });
}
function body(text: string, indent = 0): Paragraph {
    return new Paragraph({
        children: [new TextRun({ text, size: 24, font: "Calibri", color: "333333" })],
        indent: indent ? { left: indent } : undefined,
        spacing: { after: 80 },
    });
}
function bullet(text: string, indent = 360): Paragraph {
    return new Paragraph({
        children: [new TextRun({ text: `• ${text}`, size: 24, font: "Calibri", color: "333333" })],
        indent: { left: indent },
        spacing: { after: 60 },
    });
}
function kv(label: string, value: string): Paragraph {
    return new Paragraph({
        children: [
            new TextRun({ text: `${label}: `, bold: true, font: "Calibri", size: 24 }),
            new TextRun({ text: value, font: "Calibri", size: 24, color: "333333" }),
        ],
        spacing: { after: 80 },
    });
}
function divider(): Paragraph {
    return new Paragraph({ text: "", spacing: { before: 200, after: 200 } });
}

export const gtmDocxGenerator = {
    /**
     * Generates a professional Go-to-Market Plan Word document.
     * Bilingual: uses data as-is (labels pre-translated by AI).
     */
    generate: async (data: GTMData, lang: 'es' | 'en' = 'en') => {
        const projectName = data.projectName || 'GTM Plan';
        const L = {
            coverSubtitle: lang === 'es' ? 'Plan de Go-to-Market' : 'Go-to-Market Plan',
            generatedBy: lang === 'es' ? 'Generado por PILOTAI' : 'Generated by PILOTAI',
            executiveSummary: lang === 'es' ? 'Resumen Ejecutivo' : 'Executive Summary',
            industryBenchmarks: lang === 'es' ? 'Benchmarks de Industria' : 'Industry Benchmarks',
            vertical: lang === 'es' ? 'Vertical' : 'Vertical',
            avgCPC: lang === 'es' ? 'CPC Promedio' : 'Avg. CPC',
            avgConv: lang === 'es' ? 'Tasa de Conversión Promedio' : 'Avg. Conversion Rate',
            avgCAC: lang === 'es' ? 'CAC Promedio' : 'Avg. CAC',
            avgLTV: lang === 'es' ? 'LTV Promedio' : 'Avg. LTV',
            source: lang === 'es' ? 'Fuente' : 'Source',
            buyerPersona: lang === 'es' ? 'Buyer Persona' : 'Buyer Persona',
            painPoint: lang === 'es' ? 'Problema principal' : 'Main Pain Point',
            interests: lang === 'es' ? 'Intereses' : 'Interests',
            behaviors: lang === 'es' ? 'Comportamientos' : 'Behaviors',
            goals: lang === 'es' ? 'Objetivos' : 'Goals',
            objections: lang === 'es' ? 'Objeciones' : 'Objections',
            messaging: lang === 'es' ? 'Messaging Framework' : 'Messaging Framework',
            valueProp: lang === 'es' ? 'Propuesta de Valor' : 'Value Proposition',
            pitch: lang === 'es' ? 'Elevator Pitch (30s)' : 'Elevator Pitch (30s)',
            tagline: lang === 'es' ? 'Tagline' : 'Tagline',
            keyMessages: lang === 'es' ? 'Mensajes Clave por Audiencia' : 'Key Messages by Audience',
            roasScenarios: lang === 'es' ? 'Escenarios ROAS' : 'ROAS Scenarios',
            conservative: lang === 'es' ? 'Conservador' : 'Conservative',
            base: lang === 'es' ? 'Base' : 'Base',
            aggressive: lang === 'es' ? 'Agresivo' : 'Aggressive',
            unitEconomics: lang === 'es' ? 'Unit Economics' : 'Unit Economics',
            cac: lang === 'es' ? 'Costo de Adquisición (CAC)' : 'Customer Acquisition Cost (CAC)',
            ltv: lang === 'es' ? 'Valor de Vida del Cliente (LTV)' : 'Lifetime Value (LTV)',
            ltvCac: lang === 'es' ? 'Ratio LTV / CAC' : 'LTV / CAC Ratio',
            payback: lang === 'es' ? 'Período de Recuperación' : 'Payback Period',
            churn: lang === 'es' ? 'Churn Mensual' : 'Monthly Churn',
            arpu: lang === 'es' ? 'Ingreso Promedio por Usuario' : 'ARPU',
            months: lang === 'es' ? 'meses' : 'months',
            channelStrategy: lang === 'es' ? 'Estrategia de Canales (Priorización ICE)' : 'Channel Strategy (ICE Prioritization)',
            recommended: lang === 'es' ? 'RECOMENDADO' : 'RECOMMENDED',
            gtmCalendar: lang === 'es' ? 'Calendario Go-to-Market (12 Semanas)' : 'Go-to-Market Calendar (12 Weeks)',
            funnel: lang === 'es' ? 'Funnel Táctico' : 'Tactical Funnel',
            footer: lang === 'es' ? `Generado por PILOTAI — ${new Date().toLocaleDateString('es-AR')} — Método: GTM Framework` : `Generated by PILOTAI — ${new Date().toLocaleDateString('en-US')} — Method: GTM Framework`,
        };

        const sections: Paragraph[] = [];

        // ── COVER ─────────────────────────────────────────────────────────
        sections.push(
            new Paragraph({
                children: [new TextRun({ text: projectName, bold: true, size: 72, color: "1E293B", font: "Calibri" })],
                alignment: AlignmentType.CENTER,
                spacing: { before: 4000, after: 300 },
            }),
            new Paragraph({
                children: [new TextRun({ text: L.coverSubtitle, size: 36, color: "EC4899", font: "Calibri" })],
                alignment: AlignmentType.CENTER,
                spacing: { after: 200 },
            }),
            new Paragraph({
                children: [new TextRun({ text: `${new Date().toLocaleDateString(lang === 'es' ? 'es-AR' : 'en-US', { year: 'numeric', month: 'long', day: 'numeric' })}`, size: 24, italics: true, color: "888888", font: "Calibri" })],
                alignment: AlignmentType.CENTER,
                spacing: { after: 200 },
            }),
            new Paragraph({
                children: [
                    new TextRun({ text: L.generatedBy, size: 20, color: "AAAAAA", font: "Calibri" }),
                    new PageBreak(),
                ],
                alignment: AlignmentType.CENTER,
            }),
        );

        // ── 1. EXECUTIVE SUMMARY ──────────────────────────────────────────
        if (data.summary) {
            sections.push(h1(L.executiveSummary));
            sections.push(body(data.summary));
            sections.push(divider());
        }

        // ── 2. INDUSTRY BENCHMARKS ────────────────────────────────────────
        if (data.industryBenchmarks) {
            const b = data.industryBenchmarks;
            sections.push(h1(L.industryBenchmarks, true));
            if (b.vertical) sections.push(kv(L.vertical, b.vertical));
            if (b.avgCPC !== undefined) sections.push(kv(L.avgCPC, `$${b.avgCPC.toFixed(2)}`));
            if (b.avgConversionRate !== undefined) sections.push(kv(L.avgConv, `${(b.avgConversionRate * 100).toFixed(1)}%`));
            if (b.avgCAC !== undefined) sections.push(kv(L.avgCAC, `$${b.avgCAC.toLocaleString()}`));
            if (b.avgLTV !== undefined) sections.push(kv(L.avgLTV, `$${b.avgLTV.toLocaleString()}`));
            if (b.source) sections.push(kv(L.source, b.source));
            sections.push(divider());
        }

        // ── 3. BUYER PERSONA ──────────────────────────────────────────────
        if (data.buyerPersona) {
            const p = data.buyerPersona;
            sections.push(h1(L.buyerPersona));
            if (p.avatar) sections.push(h2(p.avatar));
            if (p.painPoint) sections.push(kv(L.painPoint, p.painPoint));
            if (p.demographics) {
                for (const [k, v] of Object.entries(p.demographics)) {
                    sections.push(kv(k.charAt(0).toUpperCase() + k.slice(1), String(v)));
                }
            }
            if (p.interests?.length) {
                sections.push(body(L.interests + ':'));
                p.interests.forEach(i => sections.push(bullet(i)));
            }
            if (p.behaviors?.length) {
                sections.push(body(L.behaviors + ':'));
                p.behaviors.forEach(b => sections.push(bullet(b)));
            }
            if (p.goals?.length) {
                sections.push(body(L.goals + ':'));
                p.goals.forEach(g => sections.push(bullet(g)));
            }
            if (p.objections?.length) {
                sections.push(body(L.objections + ':'));
                p.objections.forEach(o => sections.push(bullet(o, 720)));
            }
            sections.push(divider());
        }

        // ── 4. MESSAGING FRAMEWORK ────────────────────────────────────────
        if (data.messagingFramework) {
            const m = data.messagingFramework;
            sections.push(h1(L.messaging, true));
            if (m.valueProposition) {
                sections.push(h2(L.valueProp));
                sections.push(new Paragraph({
                    children: [new TextRun({ text: m.valueProposition, italics: true, font: "Calibri", size: 24 })],
                    indent: { left: 720 }, spacing: { after: 200 },
                }));
            }
            if (m.elevatorPitch) {
                sections.push(h2(L.pitch));
                sections.push(body(m.elevatorPitch, 720));
            }
            if (m.tagline) {
                sections.push(h2(L.tagline));
                sections.push(new Paragraph({
                    children: [new TextRun({ text: `"${m.tagline}"`, bold: true, size: 30, color: "EC4899", font: "Calibri" })],
                    indent: { left: 720 }, spacing: { after: 300 },
                }));
            }
            if (m.keyMessages?.length) {
                sections.push(h2(L.keyMessages));
                m.keyMessages.forEach(km => {
                    sections.push(new Paragraph({
                        children: [new TextRun({ text: `${km.audience}`, bold: true, font: "Calibri", size: 24, color: "BE185D" })],
                        indent: { left: 360 }, spacing: { after: 40 },
                    }));
                    sections.push(body(km.message, 720));
                    sections.push(new Paragraph({
                        children: [new TextRun({ text: `Tone: ${km.tone}`, italics: true, color: "64748B", size: 20, font: "Calibri" })],
                        indent: { left: 720 }, spacing: { after: 160 },
                    }));
                });
            }
            sections.push(divider());
        }

        // ── 5. ROAS SCENARIOS ─────────────────────────────────────────────
        if (data.roasScenarios) {
            sections.push(h1(L.roasScenarios, true));
            const scenarios = [
                { label: L.conservative, data: data.roasScenarios.conservative, color: "C0392B" },
                { label: L.base, data: data.roasScenarios.base, color: "D97706" },
                { label: L.aggressive, data: data.roasScenarios.aggressive, color: "16A34A" },
            ];
            scenarios.forEach(sc => {
                if (!sc.data) return;
                sections.push(new Paragraph({
                    children: [new TextRun({ text: `── ${sc.label} ──`, bold: true, color: sc.color, size: 26, font: "Calibri" })],
                    spacing: { before: 200, after: 80 },
                }));
                sections.push(kv('ROAS', `${sc.data.roas.toFixed(1)}x`));
                sections.push(kv(lang === 'es' ? 'Ventas Mensuales' : 'Monthly Sales', `$${sc.data.monthlySales.toLocaleString()}`));
                sections.push(kv('CPC', `$${sc.data.cpc.toFixed(2)}`));
                sections.push(kv(lang === 'es' ? 'Tasa de Conversión' : 'Conversion Rate', `${(sc.data.convRate * 100).toFixed(1)}%`));
            });
            sections.push(divider());
        }

        // ── 6. UNIT ECONOMICS ─────────────────────────────────────────────
        if (data.unitEconomics) {
            const ue = data.unitEconomics;
            sections.push(h1(L.unitEconomics));
            if (ue.cac !== undefined) sections.push(kv(L.cac, `$${ue.cac.toLocaleString()}`));
            if (ue.ltv !== undefined) sections.push(kv(L.ltv, `$${ue.ltv.toLocaleString()}`));
            if (ue.ltvCacRatio !== undefined) sections.push(kv(L.ltvCac, `${ue.ltvCacRatio.toFixed(1)}x`));
            if (ue.paybackMonths !== undefined) sections.push(kv(L.payback, `${ue.paybackMonths} ${L.months}`));
            if (ue.monthlyChurn !== undefined) sections.push(kv(L.churn, `${(ue.monthlyChurn * 100).toFixed(1)}%`));
            if (ue.arpu !== undefined) sections.push(kv(L.arpu, `$${ue.arpu.toLocaleString()}`));
            sections.push(divider());
        }

        // ── 7. CHANNEL STRATEGY ───────────────────────────────────────────
        if (data.channelStrategy?.length) {
            sections.push(h1(L.channelStrategy, true));
            data.channelStrategy.forEach((ch, i: number) => {
                sections.push(new Paragraph({
                    children: [
                        new TextRun({ text: `${i + 1}. ${ch.canal}`, bold: true, size: 24, font: "Calibri", color: ch.recommended ? "BE185D" : "1E293B" }),
                        new TextRun({ text: ch.recommended ? `  [${L.recommended}]` : '', bold: true, color: "EC4899", size: 20, font: "Calibri" }),
                    ],
                    indent: { left: 360 }, spacing: { before: 160, after: 40 },
                }));
                sections.push(kv('  ICE Score', String(ch.score)));
                if (ch.budgetPct !== undefined) sections.push(kv('  Budget %', `${ch.budgetPct}%`));
                if (ch.rationale) sections.push(body(`  → ${ch.rationale}`, 720));
            });
            sections.push(divider());
        }

        // ── 8. GTM CALENDAR ───────────────────────────────────────────────
        if (data.gtmCalendar?.length) {
            sections.push(h1(L.gtmCalendar, true));
            data.gtmCalendar.forEach(week => {
                const weekLabel = typeof week.week === 'number' ? `Week ${week.week}` : week.week;
                sections.push(new Paragraph({
                    children: [
                        new TextRun({ text: `${weekLabel}${week.phase ? ` — ${week.phase}` : ''}`, bold: true, size: 24, font: "Calibri", color: "1E293B" }),
                    ],
                    spacing: { before: 160, after: 40 },
                }));
                const tasks = week.tasks || week.subtasks || [];
                tasks.forEach(task => sections.push(bullet(task)));
            });
            sections.push(divider());
        }

        // ── 9. TACTICAL FUNNEL ────────────────────────────────────────────
        if (data.tacticalFunnel?.length) {
            sections.push(h1(L.funnel, true));
            data.tacticalFunnel.forEach(step => {
                sections.push(new Paragraph({
                    children: [
                        new TextRun({ text: `[${step.stage}] `, bold: true, color: "EC4899", font: "Calibri", size: 24 }),
                        new TextRun({ text: `${step.metric}: `, bold: true, font: "Calibri", size: 24 }),
                        new TextRun({ text: `${typeof step.value === 'number' ? step.value.toLocaleString() : step.value}   `, font: "Calibri", size: 24, color: "333333" }),
                        new TextRun({ text: `Action: ${step.action}`, italics: true, font: "Calibri", size: 22, color: "64748B" }),
                    ],
                    indent: { left: 360 },
                    spacing: { after: 120 },
                }));
            });
        }

        // ── FOOTER ────────────────────────────────────────────────────────
        sections.push(divider());
        sections.push(new Paragraph({
            children: [new TextRun({ text: L.footer, italics: true, size: 18, color: "AAAAAA", font: "Calibri" })],
            alignment: AlignmentType.CENTER,
        }));

        // ── BUILD DOCUMENT ────────────────────────────────────────────────
        const doc = new Document({
            styles: {
                default: {
                    heading1: {
                        run: { font: "Calibri", size: 40, bold: true, color: "BE185D" },
                        paragraph: { spacing: { before: 300, after: 120 } },
                    },
                    heading2: {
                        run: { font: "Calibri", size: 28, bold: true, color: "1E293B" },
                        paragraph: { spacing: { before: 200, after: 80 } },
                    },
                    document: {
                        run: { font: "Calibri", size: 24, color: "333333" },
                    },
                },
            },
            sections: [{
                properties: {},
                children: sections,
            }],
        });

        const blob = await Packer.toBlob(doc);
        const safeName = projectName.replace(/\s+/g, '_').replace(/[^a-zA-Z0-9_-]/g, '');
        saveAs(blob, `${safeName}_GTM_Plan.docx`);
    }
};
